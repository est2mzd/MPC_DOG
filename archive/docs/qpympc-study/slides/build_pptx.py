def chap(d: Deck, code: str, md_file: str, title: str, blurb: str, first: str, bg, intent, arch, flow, note=None):
    d.section_slide(f"{code}  {md_file}", title, blurb)
    s = d.content(code, first)
    d.frame4(s, bg, intent, arch, flow)
    d.notes(s, note or NOTE.get(code.split()[0], "※ 知らない語は、この下の注釈と変数表を見る。覚えなくてよい。"))


def sec(d: Deck, code: str, heading: str, takeaway: str | None = None, note=None):
    s = d.content(code, heading, takeaway)
    if note:
        d.notes(s, note)
    elif code.split()[0] in NOTE:
        d.notes(s, NOTE[code.split()[0]])
    return s


def codes_slide(d: Deck, code: str, heading: str, files: list, next_md: str):
    s = sec(
        d,
        code,
        heading,
        "詳細は Markdown の同じ見出し。ここでは入口のファイル名だけ。",
        note="※ 対応コード=この章の処理が書いてあるプログラム。次の本文=このあと読む Markdown。",
    )
    d.bullets(s, files + [f"次に読む本文: {next_md}"], top=1.85, size=16)


