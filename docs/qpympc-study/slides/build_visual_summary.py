def place(slide, path, left, top, max_w, max_h, center=True):
    from PIL import Image

    im = Image.open(path)
    w, h = im.size
    ar = w / float(h)
    box_ar = max_w / float(max_h)
    if ar > box_ar:
        fw, fh = max_w, max_w / ar
    else:
        fw, fh = max_h * ar, max_h
    x = left + (max_w - fw) / 2.0 if center else left
    slide.shapes.add_picture(str(path), Inches(x), Inches(top), width=Inches(fw), height=Inches(fh))
    return fw, fh


def caption(slide, left, top, width, height, text, size=15):
    add_text_box(slide, Inches(left), Inches(top), Inches(width), Inches(height), text, size=size, color=INK)


